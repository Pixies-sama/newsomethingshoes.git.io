/**
 * Handles slider item rendering transformations with high-end crossfades
 */
function navigateSliderToItem(targetIndex) {
  if (carouselTransitionActive) return;
  carouselTransitionActive = true;

  const itemData = top5SliderCollection[targetIndex];

  mainSliderImg.classList.add("hidden-state");
  detailsTrayNode.classList.add("hidden-state");

  setTimeout(() => {
    sliderTitle.innerText = itemData.name;
    sliderPrice.innerText = `₦${itemData.price.toLocaleString()}`;
    sliderCategory.innerText = `SIGNATURE ${itemData.gender.toUpperCase()}`;
    sliderDesc.innerText = itemData.description;
    
    sliderSpecsList.innerHTML = itemData.specs.map(spec => `
      <li><i class="fas fa-square"></i> <span>${spec}</span></li>
    `).join("");

    sliderSkeleton.classList.add("loading");

    const assetPreloader = new Image();
    assetPreloader.src = itemData.imageUrl;

    assetPreloader.onload = () => {
      mainSliderImg.src = itemData.imageUrl;
      sliderSkeleton.classList.remove("loading");
      mainSliderImg.classList.remove("hidden-state");
      detailsTrayNode.classList.remove("hidden-state");
      carouselTransitionActive = false;
    };

    assetPreloader.onerror = () => {
      mainSliderImg.src = "https://placehold.co/600x450/f4f0ea/111111?text=New+Something";
      sliderSkeleton.classList.remove("loading");
      mainSliderImg.classList.remove("hidden-state");
      detailsTrayNode.classList.remove("hidden-state");
      carouselTransitionActive = false;
    };

    updateRibbonStripStatus(targetIndex);
    currentActiveIdx = targetIndex;
  }, 350);
}

/**
 * Renders the top 5 thumbnail selector buttons
 */
function initializeRibbonStrip() {
  if (!thumbRibbonContainer) return;

  thumbRibbonContainer.innerHTML = top5SliderCollection.map((item, index) => `
    <div class="strip-thumb-item ${index === 0 ? 'active' : ''}" data-ribbon-idx="${index}">
      <img src="${item.imageUrl}" alt="Look variant" onerror="this.onerror=null; this.src='https://placehold.co/150x150/f4f0ea/111111?text=NS';">
    </div>
  `).join("");

  document.querySelectorAll(".strip-thumb-item").forEach(el => {
    el.addEventListener("click", () => {
      const selectedIdx = parseInt(el.getAttribute("data-ribbon-idx"));
      if (selectedIdx !== currentActiveIdx) {
        navigateSliderToItem(selectedIdx);
      }
    });
  });
}

function updateRibbonStripStatus(activeIndex) {
  const elements = document.querySelectorAll(".strip-thumb-item");
  elements.forEach((el, index) => {
    if (index === activeIndex) el.classList.add("active");
    else el.classList.remove("active");
  });
}

/**
 * Automates pristine text communication queries for WhatsApp integration routing
 */
function getWhatsAppDeepLink(productName, productImg) {
  const fullImageReferencePath = productImg.startsWith('http') ? productImg : `${window.location.origin}/${productImg}`;
  const baselineMessage = `Hello Concierge Desk, I am reviewing the lookbook archive and would like to check active stock configurations for this design model:\n\n*${productName}*\n\nImage reference lookup: ${fullImageReferencePath}`;
  return `https://wa.me/${WHATSAPP_DESK_NUMBER}?text=${encodeURIComponent(baselineMessage)}`;
}

/**
 * Renders gallery items displaying Images ONLY (No text, names, or prices)
 */
function renderGalleryCards() {
  if (!galleryCardsGrid) return;

  const databaseFilteredPool = galleryFilterValue === "all"
    ? footwearCollection
    : footwearCollection.filter(item => item.gender.toLowerCase() === galleryFilterValue.toLowerCase());

  // Show exactly up to 30 elements first, reveal all on expansion button click
  const visibleSubsetPool = isExpandedShowAllActive 
    ? databaseFilteredPool 
    : databaseFilteredPool.slice(0, INITIAL_VISIBLE_CARD_COUNT);

  // If filtered collection has 30 items or fewer, conceal the pagination button container
  if (databaseFilteredPool.length <= INITIAL_VISIBLE_CARD_COUNT || isExpandedShowAllActive) {
    expansionBox.style.display = "none";
  } else {
    expansionBox.style.display = "flex";
  }

  if (visibleSubsetPool.length === 0) {
    galleryCardsGrid.innerHTML = `<div style="grid-column:1/-1; text-align:center; padding: 4rem 0; color: var(--text-muted); font-size: 0.85rem; letter-spacing:0.05em;">NO DESIGNS FOUND CURRENTLY IN THIS CATEGORY.</div>`;
    return;
  }

  // Render pure images inside structural canvas nodes with no textual elements
  galleryCardsGrid.innerHTML = visibleSubsetPool.map(shoe => `
    <div class="lookbook-item-card" data-product-id="${shoe.id}">
      <img src="${shoe.imageUrl}" alt="Footwear design frame" onerror="this.onerror=null; this.src='https://placehold.co/400x400/f4f0ea/111111?text=Footwear+Design';">
    </div>
  `).join("");

  // Bind the simplified image expansion modal viewer on click
  document.querySelectorAll(".lookbook-item-card").forEach(cardNode => {
    cardNode.addEventListener("click", () => {
      const targetId = parseInt(cardNode.getAttribute("data-product-id"));
      const selectedItemObject = footwearCollection.find(item => item.id === targetId);
      if (selectedItemObject) {
        launchProductDetailsModal(selectedItemObject);
      }
    });
  });
}

/**
 * Populates and reveals the completely streamlined, no-details minimalist image popup modal
 */
function launchProductDetailsModal(productData) {
  modalProductImage.src = productData.imageUrl;
  modalProductImage.alt = productData.name;
  modalProductImage.onerror = function() {
    this.onerror = null;
    this.src = "https://placehold.co/600x600/f4f0ea/1a1412?text=New+Something";
  };

  // Bind inquiry links directly to the single standalone bottom text button action
  const directLinkUrl = getWhatsAppDeepLink(productData.name, productData.imageUrl);
  modalInquireBtn.onclick = () => window.open(directLinkUrl, "_blank");

  productModal.classList.add("active");
  document.body.style.overflow = "hidden";
}

function closeProductDetailsModal() {
  productModal.classList.remove("active");
  document.body.style.overflow = "";
}

// Bind closing triggers safely
closeModalBtn?.addEventListener("click", closeProductDetailsModal);
productModal?.addEventListener("click", (e) => {
  if (e.target === productModal) closeProductDetailsModal();
});

